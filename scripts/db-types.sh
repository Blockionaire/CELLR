#!/usr/bin/env bash
# Regenerates apps/web/src/server/db/database.types.ts from the migrations (no Docker, no hosted project):
# applies shim + migrations + seed to a throwaway Postgres, runs `supabase gen types`, formats with Prettier.
#   pnpm db:types            write the file
#   pnpm db:types --check    fail if the committed file is out of date (used in CI)
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
# shellcheck source=lib/temp-cluster.sh
source "$ROOT/scripts/lib/temp-cluster.sh"
trap stop_temp_cluster EXIT

OUTFILE="$ROOT/apps/web/src/server/db/database.types.ts"
TMP="$(mktemp --suffix=.ts)"
start_temp_cluster 54998
apply_schema "$ROOT"
{
  echo "// GENERATED by \`pnpm db:types\` from supabase/migrations — do not edit by hand."
  (cd "$ROOT" && pnpm exec supabase gen types typescript --db-url "$PGURL" --schema public 2>/dev/null)
} > "$TMP"
(cd "$ROOT" && pnpm exec prettier --write "$TMP" >/dev/null)

if [ "${1:-}" = "--check" ]; then
  if diff -q "$TMP" "$OUTFILE" >/dev/null 2>&1; then echo "database.types.ts is up to date"; rm -f "$TMP"; exit 0; fi
  echo "database.types.ts is stale — run: pnpm db:types" >&2; rm -f "$TMP"; exit 1
fi
mkdir -p "$(dirname "$OUTFILE")"; mv "$TMP" "$OUTFILE"; echo "wrote ${OUTFILE#"$ROOT"/}"
